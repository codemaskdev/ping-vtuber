// Draws text with its top-left at (x, y); each font pixel is scale x scale image pixels.
export function drawText(img, text, x, y, scale, rgba) {
  let cx = x;
  for (const ch of String(text).toUpperCase()) {
    const rows = (GLYPHS[ch] || GLYPHS[" "]).split("|");
    for (let r = 0; r < 7; r++) {
      for (let c = 0; c < 5; c++) if (rows[r][c] === "#") fillRect(img, cx + c * scale, y + r * scale, scale, scale, rgba);
    }
    cx += 6 * scale;
  }
  return cx - x;
}

export function textWidth(text, scale) {
  return String(text).length * 6 * scale;
}
